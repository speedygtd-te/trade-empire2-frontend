// Image helpers (RGB float arrays, row-major, 3 channels)

async function readRgb(file, size) {
  let img = sharp(file).removeAlpha();
  if (size) img = img.resize(size, size, { fit: 'fill', kernel: 'lanczos3' });
  const { data, info } = await img.raw().toBuffer({ resolveWithObject: true });
  return { w: info.width, h: info.height, px: Float32Array.from(data) };
}

function toBuffer(img) {
  const out = Buffer.alloc(img.px.length);
  for (let i = 0; i < img.px.length; i++) out[i] = Math.max(0, Math.min(255, Math.round(img.px[i])));
  return out;
}

async function writeRgb(img, file, resize) {
  let s = sharp(toBuffer(img), { raw: { width: img.w, height: img.h, channels: 3 } });
  if (resize) s = s.resize(resize, resize, { kernel: 'lanczos3' });
  await s.png({ compressionLevel: 9 }).toFile(file);
}

function solve(a, b) {
  // Gaussian elimination with partial pivoting, a is n x n, b is n.
  const n = b.length;
  const m = a.map((row, i) => [...row, b[i]]);
  for (let c = 0; c < n; c++) {
    let p = c;
    for (let r = c + 1; r < n; r++) if (Math.abs(m[r][c]) > Math.abs(m[p][c])) p = r;
    [m[c], m[p]] = [m[p], m[c]];
    for (let r = 0; r < n; r++) {
      if (r === c || m[c][c] === 0) continue;
      const f = m[r][c] / m[c][c];
      for (let k = c; k <= n; k++) m[r][k] -= f * m[c][k];
    }
  }
  return m.map((row, i) => row[n] / row[i]);
}

// 1. Divide out a quadratic luminance surface fitted to 16x16 block means.
function flatten(img) {
  const { w, h, px } = img;
  const B = 16, bw = w / B, bh = h / B;
  const basis = (u, v) => [1, u, v, u * u, u * v, v * v];
  const ata = Array.from({ length: 6 }, () => new Array(6).fill(0));
  const atb = new Array(6).fill(0);
  let total = 0;
  for (let by = 0; by < B; by++) {
    for (let bx = 0; bx < B; bx++) {
      let s = 0, n = 0;
      for (let y = Math.floor(by * bh); y < Math.floor((by + 1) * bh); y++) {
        for (let x = Math.floor(bx * bw); x < Math.floor((bx + 1) * bw); x++) {
          const i = (y * w + x) * 3;
          s += 0.299 * px[i] + 0.587 * px[i + 1] + 0.114 * px[i + 2];
          n++;
        }
      }
      const l = s / n;
      total += l;
      const f = basis(((bx + 0.5) / B) * 2 - 1, ((by + 0.5) / B) * 2 - 1);
      for (let r = 0; r < 6; r++) {
        atb[r] += f[r] * l;
        for (let c = 0; c < 6; c++) ata[r][c] += f[r] * f[c];
      }
    }
  }
  const coef = solve(ata, atb);
  const mean = total / (B * B);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const f = basis(((x + 0.5) / w) * 2 - 1, ((y + 0.5) / h) * 2 - 1);
      let fit = 0;
      for (let r = 0; r < 6; r++) fit += coef[r] * f[r];
      const gain = Math.max(0.6, Math.min(1.6, mean / Math.max(fit, 1)));
      const i = (y * w + x) * 3;
      px[i] *= gain; px[i + 1] *= gain; px[i + 2] *= gain;
    }
  }
}

function channelStats(px, include) {
  const sum = [0, 0, 0], sq = [0, 0, 0];
  let n = 0;
  for (let p = 0; p < px.length / 3; p++) {
    if (include && !include(p)) continue;
    for (let c = 0; c < 3; c++) { const v = px[p * 3 + c]; sum[c] += v; sq[c] += v * v; }
    n++;
  }
  const mean = sum.map((s) => s / n);
  const sd = sq.map((s, c) => Math.sqrt(Math.max(1e-6, s / n - mean[c] * mean[c])));
  return { mean, sd, n };
}

// Mean and spread of the shipped V1 tiles of a biome (all four slots, opaque pixels only).
const v1StatsCache = new Map();
async function v1Stats(biome) {
  if (v1StatsCache.has(biome)) return v1StatsCache.get(biome);
  const parts = [];
  for (const slot of SLOTS) {
    const file = path.join(V1_TILES, biome, `${biome}_${slot}.webp`);
    if (!fs.existsSync(file)) continue;
    const { data } = await sharp(file).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    for (let p = 0; p < data.length / 4; p++) {
      if (data[p * 4 + 3] < 250) continue;
      parts.push(data[p * 4], data[p * 4 + 1], data[p * 4 + 2]);
    }
  }
  const stats = parts.length ? channelStats(Float32Array.from(parts)) : null;
  v1StatsCache.set(biome, stats);
  return stats;
}

// 2. Per-channel mean/spread transfer towards the V1 stats, strength 0..1.
function grade(img, target, strength, sdClamp = [0.6, 1.6]) {
  if (!target || strength <= 0) return;
  const src = channelStats(img.px);
  for (let c = 0; c < 3; c++) {
    const ratio = Math.max(sdClamp[0], Math.min(sdClamp[1], target.sd[c] / src.sd[c]));
    for (let p = c; p < img.px.length; p += 3) {
      const graded = (img.px[p] - src.mean[c]) * ratio + target.mean[c];
      img.px[p] = img.px[p] + (graded - img.px[p]) * strength;
    }
  }
}

function transpose(img) {
  const { w, h, px } = img;
  const out = new Float32Array(px.length);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) for (let c = 0; c < 3; c++) out[(x * h + y) * 3 + c] = px[(y * w + x) * 3 + c];
  return { w: h, h: w, px: out };
}

// 3. Makes the image wrap horizontally: width shrinks by OVERLAP. Column x < OVERLAP of the
// result is joined from P = source column N+x (continues the right edge across the wrap) and
// Q = source column x (continues into column OVERLAP). The cut runs top to bottom through the
// overlap where P and Q differ least and closes on itself, so the result still wraps
// vertically.
function wrapX(img) {
  const { w, h, px } = img;
  const k = OVERLAP, n = w - k, lo = MARGIN, hi = k - 1 - MARGIN, width = hi - lo + 1;
  const err = new Float64Array(h * width);
  for (let y = 0; y < h; y++) {
    for (let j = 0; j < width; j++) {
      const x = lo + j, a = (y * w + n + x) * 3, b = (y * w + x) * 3;
      let e = 0;
      for (let c = 0; c < 3; c++) { const d = px[a + c] - px[b + c]; e += d * d; }
      err[y * width + j] = e;
    }
  }
  let best = { cost: Infinity, path: null };
  for (let start = 0; start < width; start++) {
    let cost = new Float64Array(width).fill(Infinity);
    cost[start] = err[start];
    const from = new Int16Array(h * width);
    for (let y = 1; y < h; y++) {
      const next = new Float64Array(width);
      for (let j = 0; j < width; j++) {
        let m = cost[j], arg = j;
        if (j > 0 && cost[j - 1] < m) { m = cost[j - 1]; arg = j - 1; }
        if (j < width - 1 && cost[j + 1] < m) { m = cost[j + 1]; arg = j + 1; }
        next[j] = m + err[y * width + j];
        from[y * width + j] = arg;
      }
      cost = next;
    }
    for (let end = Math.max(0, start - 1); end <= Math.min(width - 1, start + 1); end++) {
      if (cost[end] >= best.cost) continue;
      const p = new Int16Array(h);
      p[h - 1] = end;
      for (let y = h - 1; y > 0; y--) p[y - 1] = from[y * width + p[y]];
      best = { cost: cost[end], path: p };
    }
  }
  const out = new Float32Array(n * h * 3);
  for (let y = 0; y < h; y++) {
    const cut = lo + best.path[y];
    for (let x = 0; x < n; x++) {
      const o = (y * n + x) * 3, q = (y * w + x) * 3;
      if (x >= k) { for (let c = 0; c < 3; c++) out[o + c] = px[q + c]; continue; }
      const p = (y * w + n + x) * 3;
      const wp = Math.max(0, Math.min(1, 0.5 + (cut - 0.5 - x) / (2 * FEATHER)));
      for (let c = 0; c < 3; c++) out[o + c] = px[p + c] * wp + px[q + c] * (1 - wp);
    }
  }
  return { w: n, h, px: out };
}

function makeSeamless(img) {
  return transpose(wrapX(transpose(wrapX(img))));
}

// Resamples the seamless (SIZE - OVERLAP) tile to SIZE without breaking the wrap: a plain resize
// clamps at the border, so the tile is padded with its own opposite edges first and the padding
// is cut off afterwards. 448 + 2*7 = 462 -> 528, minus 2*8 = 512.
async function writeWrapped(img, file) {
  const { w, h, px } = img;
  const scale = SIZE / w;
  const pad = 7;
  const pw = w + 2 * pad, ph = h + 2 * pad;
  const padded = new Float32Array(pw * ph * 3);
  for (let y = 0; y < ph; y++) {
    const sy = (y - pad + h) % h;
    for (let x = 0; x < pw; x++) {
      const sx = (x - pad + w) % w, o = (y * pw + x) * 3, s = (sy * w + sx) * 3;
      padded[o] = px[s]; padded[o + 1] = px[s + 1]; padded[o + 2] = px[s + 2];
    }
  }
  const big = Math.round(pw * scale), cut = Math.round(pad * scale);
  await sharp(toBuffer({ w: pw, h: ph, px: padded }), { raw: { width: pw, height: ph, channels: 3 } })
    .resize(big, big, { kernel: 'lanczos3' })
    .extract({ left: cut, top: cut, width: SIZE, height: SIZE })
    .png({ compressionLevel: 9 }).toFile(file);
}

// Largest jump across the wrap edges relative to the typical jump between neighbours inside;
// about 1 means the edge is as smooth as the texture itself.
function seamRatio(img) {
  const { w, h, px } = img;
  const diff = (a, b) => { let e = 0; for (let c = 0; c < 3; c++) e += Math.abs(px[a + c] - px[b + c]); return e; };
  let inner = 0, edge = 0;
  for (let y = 0; y < h; y++) {
    inner += diff((y * w + w / 2 - 1) * 3, (y * w + w / 2) * 3);
    edge += diff((y * w + w - 1) * 3, (y * w) * 3);
  }
  for (let x = 0; x < w; x++) {
    inner += diff(((h / 2 - 1) * w + x) * 3, ((h / 2) * w + x) * 3);
    edge += diff(((h - 1) * w + x) * 3, x * 3);
  }
  return edge / Math.max(inner, 1e-6);
}

async function processOne(biome, entry, slot) {
  let source = rawPath(biome, slot);
  if (entry.centerCrop) {
    // Some bases were generated larger and the approved tile used only the centre.
    const meta = await sharp(source).metadata();
    const c = Math.min(entry.centerCrop, meta.width, meta.height);
    source = await sharp(source).extract({ left: Math.floor((meta.width - c) / 2), top: Math.floor((meta.height - c) / 2), width: c, height: c }).png().toBuffer();
  }
  const img = await readRgb(source, SIZE);
  if (entry.flatten !== false) flatten(img);
  grade(img, await v1Stats(biome), entry.grade ?? 1, entry.sdClamp);
  const seamless = makeSeamless(img);
  await writeWrapped(seamless, finalPath(biome, slot));
  const check = await readRgb(finalPath(biome, slot));
  return seamRatio(check);
}

