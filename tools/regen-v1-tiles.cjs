async function main() {
  const args = parseArgs(process.argv.slice(2));
  const all = loadTable();
  const names = Object.keys(all).filter((b) => !args.only || args.only.includes(b));
  if (args.only) for (const b of args.only) if (!all[b]) throw new Error(`unknown biome ${b}`);
  for (const dir of [OUT, RAW, CHECK]) fs.mkdirSync(dir, { recursive: true });

  const ratioFile = path.join(OUT, 'seam-ratios.json');
  const ratios = fs.existsSync(ratioFile) ? JSON.parse(fs.readFileSync(ratioFile, 'utf8')) : {};
  const depth = Object.fromEntries(names.map((b) => [b, depthOf(all, b)]));
  const maxDepth = Math.max(0, ...Object.values(depth));

  // Edits need their input's finished square, so generate and process depth by depth; within a
  // depth, slots overridden as edits of their own slot 0 come after the others.
  for (let d = 0; d <= maxDepth; d++) {
    const level = names.filter((b) => depth[b] === d);
    for (const overridden of [false, true]) {
      const pairs = [];
      for (const b of level) for (const slot of args.slots) if (Boolean(overrideFor(all[b], slot)) === overridden) pairs.push({ b, slot });
      if (args.generate) {
        const jobs = pairs.filter((p) => args.force || !fs.existsSync(rawPath(p.b, p.slot))).map((p) => ({ ...p, label: `${p.b}_${p.slot}` }));
        if (jobs.length) console.log(`generate depth ${d}${overridden ? ' (slot overrides)' : ''}: ${jobs.length} call(s)${args.dryRun ? ' (dry run)' : ''}`);
        if (args.dryRun) {
          for (const j of jobs) { const input = inputFor(j.b, all[j.b], j.slot); console.log(`  ${j.label} seed ${seedFor(all[j.b], j.slot)}${input ? ` from ${path.basename(input)}` : ''}`); }
          continue;
        }
        let done = 0;
        const failures = await pool(jobs, args.concurrency, async (j) => {
          const seed = await generateOne(j.b, all[j.b], j.slot);
          console.log(`  [${++done}/${jobs.length}] ${j.label} seed ${seed}`);
        });
        if (failures.length) console.log(`generate: ${failures.length} failed: ${failures.map((f) => f.job.label).join(', ')}`);
      }
      if (args.process && !args.dryRun) {
        for (const { b, slot } of pairs) {
          if (!fs.existsSync(rawPath(b, slot))) continue;
          ratios[`${b}_${slot}`] = await processOne(b, all[b], slot);
        }
      }
    }
  }
  if (args.dryRun) return;
  if (args.process) {
    fs.writeFileSync(ratioFile, JSON.stringify(ratios, null, 1) + '\n');
    console.log(`process: done, manifest holds ${writeManifest(all, ratios)} tile(s)`);
  }

  if (args.check) {
    for (const b of names) await biomeSheet(b, all[b], SLOTS.map((s) => ratios[`${b}_${s}`]));
    const every = Object.keys(all);
    for (let p = 0; p * 14 < every.length; p++) await overview(all, p + 1, every.slice(p * 14, p * 14 + 14));
    console.log(`check: sheets in ${CHECK}`);
  }
}

if (require.main === module) {
  main().catch((err) => { console.error(err.stack || err.message); process.exit(1); });
}

