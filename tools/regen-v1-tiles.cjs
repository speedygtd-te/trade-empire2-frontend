// Manifest

function writeManifest(biomes, ratios) {
  const tiles = [];
  for (const [biome, e] of Object.entries(biomes)) {
    for (const slot of SLOTS) {
      if (!fs.existsSync(finalPath(biome, slot))) continue;
      const o = overrideFor(e, slot);
      const input = inputFor(biome, e, slot);
      tiles.push({
        biome, slot, endpoint: endpointFor(e, slot), prompt: promptFor(e, slot), seed: seedFor(e, slot),
        ...(input ? { inputImage: path.basename(input) } : { generatedSize: e.size }),
        file: path.relative(OUT, finalPath(biome, slot)).replace(/\\/g, '/'),
        raw: path.relative(OUT, rawPath(biome, slot)).replace(/\\/g, '/'),
        promptSource: e.source, origin: e.origin,
        variantMethod: o ? `layout edit of own slot ${o.fromSlot}`
          : e.parent ? `edit of ${e.parent}_${slot}, same prompt`
          : slot === 0 ? 'basis seed' : (e.variantPrompt ? 'variant prompt, new seed' : 'same prompt, new seed'),
        seamRatio: ratios[`${biome}_${slot}`] != null ? Number(ratios[`${biome}_${slot}`].toFixed(3)) : null,
      });
    }
  }
  fs.writeFileSync(path.join(OUT, 'manifest.json'), JSON.stringify({
    generated: new Date().toISOString(),
    size: SIZE,
    processing: [
      'flatten: quadratic luminance surface divided out (gain clamped 0.6..1.6)',
      'grade: per-channel mean/sd matched to the shipped V1 tiles of the biome (sd ratio clamped 0.6..1.6 unless the biome sets sdClamp, strength per biome)',
      `seamless: wrap-overlap ${OVERLAP}px per axis, minimum-error cut closed on the torus, ${FEATHER}px feather, ${SIZE - OVERLAP}px resampled to ${SIZE}px (lanczos3)`,
    ],
    tiles,
  }, null, 2) + '\n');
  return tiles.length;
}

