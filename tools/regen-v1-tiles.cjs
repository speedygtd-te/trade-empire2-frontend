const DIAMOND = Buffer.from(
  `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="256"><polygon points="256,0 512,128 256,256 0,128" fill="white"/></svg>`);

// Same as the V1 pipeline: squish the square to 512x256, cut the diamond.
async function diamondOf(file) {
  const resized = await sharp(file).resize(512, 256, { fit: 'fill' }).ensureAlpha().png().toBuffer();
  const mask = await sharp(DIAMOND).resize(512, 256).ensureAlpha().png().toBuffer();
  return sharp(resized).composite([{ input: mask, blend: 'dest-in' }]).png().toBuffer();
}

async function mosaic(file, tile) {
  const t = await sharp(file).resize(tile, tile).png().toBuffer();
  const parts = [];
  for (let y = 0; y < 3; y++) for (let x = 0; x < 3; x++) parts.push({ input: t, left: x * tile, top: y * tile });
  return sharp({ create: { width: tile * 3, height: tile * 3, channels: 3, background: '#000' } }).composite(parts).png().toBuffer();
}

function label(text, width, height = 22) {
  const esc = text.replace(/&/g, '&amp;').replace(/</g, '&lt;');
  return Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}"><text x="6" y="${height - 6}" font-family="Arial" font-size="15" fill="#e6e6e6">${esc}</text></svg>`);
}

const BG = { r: 20, g: 23, b: 28, alpha: 1 };

async function biomeSheet(biome, entry, ratios) {
  const parts = [];
  const head = 22;
  const v1 = path.join(V1_TILES, biome, `${biome}_0.webp`);
  const cells = [
    ['V1 slot 0 (shipped)', fs.existsSync(v1) ? await sharp(v1).png().toBuffer() : null],
    ['new slot 0 raw, diamond', fs.existsSync(rawPath(biome, 0)) ? await diamondOf(rawPath(biome, 0)) : null],
    ['new slot 0 final, diamond', fs.existsSync(finalPath(biome, 0)) ? await diamondOf(finalPath(biome, 0)) : null],
  ];
  cells.forEach(([text, buf], i) => {
    parts.push({ input: label(text, 512), left: i * 512, top: 0 });
    if (buf) parts.push({ input: buf, left: i * 512, top: head });
  });
  const top2 = head + 256 + 8;
  for (const slot of SLOTS) {
    const f = finalPath(biome, slot);
    const r = ratios[slot] != null ? ` seam ${ratios[slot].toFixed(2)}` : '';
    parts.push({ input: label(`slot ${slot} 3x3${r}`, 384), left: slot * 384, top: top2 });
    if (fs.existsSync(f)) parts.push({ input: await mosaic(f, 128), left: slot * 384, top: top2 + head });
  }
  parts.push({ input: label(`${biome} - ${entry.source}`, 1536), left: 0, top: top2 + head + 384 });
  await sharp({ create: { width: 1536, height: top2 + head + 384 + head, channels: 4, background: BG } })
    .composite(parts).jpeg({ quality: 88 }).toFile(path.join(CHECK, `${biome}.jpg`));
}

async function overview(biomes, page, names) {
  const rowH = 128 + 22, w = 256 * 3 + 128 * 4 + 16;
  const parts = [];
  for (let i = 0; i < names.length; i++) {
    const b = names[i], top = i * rowH;
    parts.push({ input: label(`${b} (${biomes[b].source})`, w), left: 0, top });
    const v1 = path.join(V1_TILES, b, `${b}_0.webp`);
    const cells = [
      fs.existsSync(v1) ? await sharp(v1).resize(256, 128).png().toBuffer() : null,
      fs.existsSync(rawPath(b, 0)) ? await sharp(await diamondOf(rawPath(b, 0))).resize(256, 128).png().toBuffer() : null,
      fs.existsSync(finalPath(b, 0)) ? await sharp(await diamondOf(finalPath(b, 0))).resize(256, 128).png().toBuffer() : null,
    ];
    cells.forEach((buf, j) => { if (buf) parts.push({ input: buf, left: j * 256, top: top + 22 }); });
    for (const slot of SLOTS) {
      const f = finalPath(b, slot);
      if (fs.existsSync(f)) parts.push({ input: await sharp(f).resize(128, 128).png().toBuffer(), left: 768 + 16 + slot * 128, top: top + 22 });
    }
  }
  await sharp({ create: { width: w, height: names.length * rowH, channels: 4, background: BG } })
    .composite(parts).jpeg({ quality: 85 }).toFile(path.join(CHECK, `overview_${page}.jpg`));
}

