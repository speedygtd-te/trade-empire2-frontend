// Regenerates the V1 biome ground tiles as square top-down textures with fal.ai, for the
// ground atlas of the Godot client. V1 only kept the isometric diamonds (512x256); the square
// originals are lost. Each biome is regenerated from the prompt of its approved basis
// (tools/v1-tile-prompts.json): slot 0 with the basis seed, slots 1-3 with the same prompt and
// new seeds. Biomes whose approved look came from a kontext edit of another biome carry a
// `parent`: their slot n is that one edit (approved edit prompt and seed) applied to the new
// square of parent slot n, so parents are built first. Nothing here touches the game; the
// output is local asset data under assets/.
//
//   node tools/regen-v1-tiles.cjs                 generate missing raws, process, check
//   node tools/regen-v1-tiles.cjs --only beach,mesa --slots 0
//   node tools/regen-v1-tiles.cjs --process       only post-process existing raws (no fal calls)
//   node tools/regen-v1-tiles.cjs --check         only rebuild the contact sheets
//   node tools/regen-v1-tiles.cjs --force         regenerate raws even if they exist
//   node tools/regen-v1-tiles.cjs --dry-run       show what would be generated
//
// Output (assets/ is git-ignored on purpose):
//   assets/tiles-square/raw/<biome>_<n>.png        as generated by fal.ai
//   assets/tiles-square/<biome>_<n>.png            512x512, flattened, graded to V1, seamless
//   assets/tiles-square/manifest.json              biome, slot, endpoint, prompt, seed, file
//   assets/tiles-square/generations.jsonl          one line per paid fal call (budget)
//   assets/tiles-square/check/<biome>.jpg          V1 diamond vs new diamond + 3x3 mosaics
//   assets/tiles-square/check/overview_<p>.jpg     all biomes, one row each
//
// Post-processing of a raw tile, in this order:
//   1. flatten: divide out a quadratic luminance surface (flux bakes a light ramp and
//      vignette into every tile; on a repeating square it reads as a checkerboard).
//   2. grade: match per-channel mean and spread to the shipped V1 tiles of the biome
//      (V1 graded most tiles after generation; this restores that look without a new call).
//   3. seamless: wrap-overlap with a minimum-error cut, per axis. The last OVERLAP pixels are
//      laid over the first ones and the two copies are joined along the path where they
//      differ least (closed on the torus), with a 3 px feather. The tile shrinks to
//      512 - OVERLAP and is resampled back to 512 (Lanczos, factor 1.14). No content is
//      mirrored or duplicated, and there is no wide blend band.
'use strict';

const fs = require('fs');
const path = require('path');
const { ROOT, runQueued, download } = require(path.join(__dirname, '..', 'scripts', '3d', 'fal-queue.cjs'));
const sharp = require(require.resolve('sharp', { paths: [path.join(ROOT, 'scripts')] }));

const TABLE = path.join(ROOT, 'tools', 'v1-tile-prompts.json');
const OUT = path.join(ROOT, 'assets', 'tiles-square');
const RAW = path.join(OUT, 'raw');
const CHECK = path.join(OUT, 'check');
const V1_TILES = 'F:\\Trade Empire\\Frontend\\src\\assets\\tiles';
const SLOTS = [0, 1, 2, 3];
const SIZE = 512;
const OVERLAP = 64;
const FEATHER = 3;
const MARGIN = 4;

// ---------------------------------------------------------------------------------------------
// Arguments and table

function parseArgs(argv) {
  const args = { only: null, slots: SLOTS, generate: true, process: true, check: true, force: false, dryRun: false, concurrency: 4 };
  const modes = [];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--only') args.only = argv[++i].split(',').map((s) => s.trim()).filter(Boolean);
    else if (a === '--slots') args.slots = argv[++i].split(',').map((s) => Number.parseInt(s, 10));
    else if (a === '--concurrency') args.concurrency = Number.parseInt(argv[++i], 10);
    else if (a === '--force') args.force = true;
    else if (a === '--dry-run') args.dryRun = true;
    else if (a === '--generate' || a === '--process' || a === '--check') modes.push(a.slice(2));
    else throw new Error(`unknown argument ${a}`);
  }
  if (modes.length) {
    args.generate = modes.includes('generate');
    args.process = modes.includes('process');
    args.check = modes.includes('check');
  }
  return args;
}

function loadTable() {
  const table = JSON.parse(fs.readFileSync(TABLE, 'utf8'));
  const defaults = table.defaults || {};
  const biomes = {};
  for (const [name, entry] of Object.entries(table.biomes)) {
    const e = { ...defaults, ...entry };
    if (!e.prompt) throw new Error(`${name}: prompt missing`);
    if (!Array.isArray(e.variantSeeds) || e.variantSeeds.length !== 3) throw new Error(`${name}: variantSeeds must hold 3 seeds`);
    biomes[name] = e;
  }
  return biomes;
}

// A slot override ({ endpoint, prompt, seed, fromSlot }) turns one variant into an edit of the
// same biome's finished square `fromSlot` - used where every new seed drew a central motif.
function overrideFor(entry, slot) {
  return (entry.slotOverrides && entry.slotOverrides[String(slot)]) || null;
}

function seedFor(entry, slot) {
  const o = overrideFor(entry, slot);
  if (o) return o.seed;
  return slot === 0 ? entry.seed : entry.variantSeeds[slot - 1];
}

// Slot 0 always uses the basis prompt; an entry may give slots 1-3 their own (see `variantPrompt`).
function promptFor(entry, slot) {
  const o = overrideFor(entry, slot);
  if (o) return o.prompt;
  return slot > 0 && entry.variantPrompt ? entry.variantPrompt : entry.prompt;
}

function rawPath(biome, slot) { return path.join(RAW, `${biome}_${slot}.png`); }
function finalPath(biome, slot) { return path.join(OUT, `${biome}_${slot}.png`); }

// ---------------------------------------------------------------------------------------------
// Generation

// Text-to-image entries carry `size`; edit entries carry `parent` and send the parent biome's
// finished square of the same slot as the input image (one kontext call, not the old chain).
function inputFor(biome, entry, slot) {
  const o = overrideFor(entry, slot);
  if (o) return finalPath(biome, o.fromSlot);
  return entry.parent ? finalPath(entry.parent, slot) : null;
}

function endpointFor(entry, slot) {
  const o = overrideFor(entry, slot);
  return o ? o.endpoint : entry.endpoint;
}

function requestBody(biome, entry, slot) {
  const common = { prompt: promptFor(entry, slot), num_images: 1, output_format: 'png', seed: seedFor(entry, slot) };
  const inputFile = inputFor(biome, entry, slot);
  if (inputFile) {
    const input = fs.readFileSync(inputFile).toString('base64');
    return { ...common, image_url: `data:image/png;base64,${input}`, safety_tolerance: '5', ...(entry.extra || {}) };
  }
  const [w, h] = entry.size;
  return { ...common, image_size: { width: w, height: h }, enable_safety_checker: false, ...(entry.extra || {}) };
}

// 0 for text-to-image biomes, parent depth + 1 for edits.
function depthOf(biomes, name, seen = new Set()) {
  const e = biomes[name];
  if (!e.parent) return 0;
  if (seen.has(name)) throw new Error(`parent cycle at ${name}`);
  if (!biomes[e.parent]) throw new Error(`${name}: unknown parent ${e.parent}`);
  seen.add(name);
  return depthOf(biomes, e.parent, seen) + 1;
}

async function generateOne(biome, entry, slot) {
  const inputFile = inputFor(biome, entry, slot);
  if (inputFile && !fs.existsSync(inputFile)) throw new Error(`input ${path.basename(inputFile)} not built yet`);
  const body = requestBody(biome, entry, slot);
  const endpoint = endpointFor(entry, slot);
  const started = Date.now();
  const result = await runQueued(endpoint, body);
  const url = result.images && result.images[0] && result.images[0].url;
  // A submitted request is paid whether or not it returns an image, so log it first.
  fs.appendFileSync(path.join(OUT, 'generations.jsonl'), JSON.stringify({
    time: new Date().toISOString(), biome, slot, endpoint, seed: body.seed, input: inputFile ? path.basename(inputFile) : null,
    returnedSeed: result.seed ?? null, width: result.images?.[0]?.width ?? null, height: result.images?.[0]?.height ?? null,
    ok: Boolean(url), ms: Date.now() - started,
  }) + '\n');
  if (!url) throw new Error(`no image in response: ${JSON.stringify(result).slice(0, 300)}`);
  const tmp = rawPath(biome, slot) + '.download';
  await download(url, tmp);
  await sharp(tmp).png().toFile(rawPath(biome, slot));
  fs.unlinkSync(tmp);
  return result.seed ?? body.seed;
}

async function pool(jobs, concurrency, run) {
  let next = 0;
  const failures = [];
  async function worker() {
    while (next < jobs.length) {
      const job = jobs[next++];
      try { await run(job); } catch (err) { failures.push({ job, error: err.message }); console.error(`  FAIL ${job.label}: ${err.message}`); }
    }
  }
  await Promise.all(Array.from({ length: Math.max(1, concurrency) }, worker));
  return failures;
}

