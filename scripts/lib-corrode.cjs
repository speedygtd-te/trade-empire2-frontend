/**
 * MATERIAL TOOLS for metallic_surface.
 *
 * THE PROBLEM WITH A GLOBAL B/R TARGET
 *   Rudi wants TWO hues at once -- bluish steel with reddish corrosion on it.
 *   A single B/R target averages them into brown-grey; that is arithmetic, not
 *   opinion. So the hue becomes a FIELD with a per-pixel target, exactly the
 *   way brightness has been a field since flatten() existed.
 *
 * AND THE TRAP THAT FOLLOWS
 *   chromaFlatten() removes colour variation -- which is what we now WANT.
 *   The two things must be told apart, and they are different numbers:
 *     cbPP  = the fitted PLANE through the block colours    -> unwanted, out
 *     cbSd  = the sd of the block colours AFTER the plane   -> wanted, in
 *   A gradient is high cbPP / low cbSd. A mottled surface is the reverse.
 *   lib-chroma already returns both; nothing here needed inventing, only
 *   naming and a corpus band (see ast-patch-corpus.cjs).
 *
 * TILEABLE NOISE, PROVABLY
 *   A 512x256 diamond tiles the plane on the lattice generated by
 *   a1 = (512,0) and a2 = (256,128). A field is periodic on that torus iff it
 *   is built only from wave vectors of the DUAL lattice, k = m*b1 + n*b2 with
 *     b1 = 2pi*( 1/512, -1/256 )      b2 = 2pi*( 0, 1/128 )
 *   (b_i . a_j = 2pi delta_ij, checked numerically in selfTest()).
 *   So the noise is a sum of cosines on that dual lattice with random phases:
 *   band-limited, seamless BY CONSTRUCTION, no wrap blur, no resampling.
 *   That is the whole reason to go procedural -- a flux corrosion layer would
 *   have to have its tiling re-established, and LESSONS 5 already showed
 *   kontext hands back less relief than the source.
 *
 * EVERY OPERATION HERE HOLDS PER-PIXEL Rec709 LUMA EXACTLY
 *   corrode() only moves hue, so p70, sd, ramp, micro4, micro8 and MESO cannot
 *   move. Measured, not asserted -- see the "colour only" row in ast-metal.cjs.
 */

const S = require('./lib-tile-metrics.cjs');
const G = require('./lib-grain.cjs');
const L709 = S.L709;

const TWO_PI = Math.PI * 2;

/** dual-lattice basis of the 512x256 iso torus */
function dualBasis(w, h) {
  // a1=(w,0) a2=(w/2,h)  ->  B = 2pi (A^-1)^T
  return { b1: [TWO_PI / w, -TWO_PI / (2 * h)], b2: [0, TWO_PI / h] };
}
function selfTest(w, h) {
  const { b1, b2 } = dualBasis(w, h);
  const a1 = [w, 0], a2 = [w / 2, h];
  const dot = (u, v) => u[0] * v[0] + u[1] * v[1];
  return { b1a1: dot(b1, a1) / TWO_PI, b1a2: dot(b1, a2) / TWO_PI,
    b2a1: dot(b2, a1) / TWO_PI, b2a2: dot(b2, a2) / TWO_PI };   // want 1,0,0,1
}
/**
 * Band-limited noise that is EXACTLY periodic on the iso torus.
 * lamMin/lamMax are wavelengths in px; nWaves cosines, random phases.
 * Returned normalised to mean 0, sd 1.
 */
function torusNoise(w, h, lamMin, lamMax, nWaves, seed) {
  const { b1, b2 } = dualBasis(w, h);
  const rnd = S.mulberry32(seed);
  const kmaxLen = TWO_PI / lamMin, kminLen = TWO_PI / lamMax;
  // enumerate dual-lattice points inside the annulus
  const cand = [];
  const M = Math.ceil(kmaxLen / Math.min(Math.hypot(b1[0], b1[1]), Math.hypot(b2[0], b2[1]))) + 2;
  for (let m = -M; m <= M; m++) for (let n = -M; n <= M; n++) {
    if (m === 0 && n === 0) continue;
    const kx = m * b1[0] + n * b2[0], ky = m * b1[1] + n * b2[1];
    const len = Math.hypot(kx, ky);
    if (len < kminLen || len > kmaxLen) continue;
    cand.push([kx, ky, len]);
  }
  if (!cand.length) throw new Error('torusNoise: empty band ' + lamMin + '..' + lamMax);
  const pick = [];
  for (let i = 0; i < nWaves; i++) pick.push(cand[Math.floor(rnd() * cand.length)]);
  const F = new Float32Array(w * h);
  for (const k of pick) {
    const ph = rnd() * TWO_PI;
    // 1/f weighting so the long waves dominate, like real staining
    const amp = 1 / Math.pow(k[2] / kminLen, 0.9);
    for (let y = 0; y < h; y++) {
      const base = y * w, ky = k[1] * y + ph;
      for (let x = 0; x < w; x++) F[base + x] += amp * Math.cos(k[0] * x + ky);
    }
  }
  let s = 0, q = 0;
  for (let p = 0; p < w * h; p++) { s += F[p]; q += F[p] * F[p]; }
  const mu = s / (w * h), sd = Math.sqrt(Math.max(1e-9, q / (w * h) - mu * mu));
  for (let p = 0; p < w * h; p++) F[p] = (F[p] - mu) / sd;
  return F;
}
const smooth = (t) => (t <= 0 ? 0 : t >= 1 ? 1 : t * t * (3 - 2 * t));

/**
 * The corrosion MASK, 0 = bare steel, 1 = full rust.
 *   cover  target rust coverage (fraction of opaque pixels with mask > 0.5)
 *   crackW how much the tile's OWN dark crevices attract rust (0 = pure noise)
 * Rust in the cracks is not decoration -- it is where water and oxide sit, and
 * it ties the colour to the geometry that is already there instead of laying an
 * unrelated pattern on top.
 */
function corrosionMask(src, ch, w, h, cover, crackW, seed) {
  const N1 = torusNoise(w, h, 40, 260, 70, seed);
  const N2 = torusNoise(w, h, 12, 46, 70, seed + 977);
  const L = new Float32Array(w * h), A = new Uint8Array(w * h);
  for (let p = 0; p < w * h; p++) {
    L[p] = L709(src[p * ch], src[p * ch + 1], src[p * ch + 2]);
    A[p] = src[p * ch + 3] >= 250 ? 1 : 0;
  }
  // crevice term: how far below the local mean a pixel sits, r10
  const bl = G.blurOpaque(L, A, w, h, 10);
  let cs = 0, cq = 0, cn = 0;
  const CR = new Float32Array(w * h);
  for (let p = 0; p < w * h; p++) { if (!A[p]) continue; CR[p] = bl[p] - L[p]; cs += CR[p]; cq += CR[p] * CR[p]; cn++; }
  const cm = cs / cn, csd = Math.sqrt(Math.max(1e-9, cq / cn - cm * cm));
  const raw = new Float32Array(w * h);
  for (let p = 0; p < w * h; p++) raw[p] = (1 - crackW) * (0.78 * N1[p] + 0.22 * N2[p]) + crackW * ((CR[p] - cm) / csd);
  // pick the threshold that hits the requested coverage, on opaque pixels only
  const v = [];
  for (let p = 0; p < w * h; p++) if (A[p]) v.push(raw[p]);
  v.sort((a, b) => a - b);
  const thr = v[Math.min(v.length - 1, Math.floor(v.length * (1 - cover)))];
  const spread = 0.85;
  const M = new Float32Array(w * h);
  for (let p = 0; p < w * h; p++) M[p] = A[p] ? smooth((raw[p] - thr) / spread + 0.5) : 0;
  return M;
}
/**
 * Paint the two materials. Per-pixel target ratios interpolate steel -> rust
 * along the mask; R,G,B are rescaled onto that target and the per-pixel Rec709
 * luma is restored exactly, so nothing but hue moves.
 * Returns {buf, clipped} -- clipped counts pixels a channel had to be clamped
 * on, which is the only way this can bite.
 */
function corrode(src, ch, w, h, M, steel, rust) {
  const out = Buffer.from(src);
  let clipped = 0;
  for (let p = 0; p < w * h; p++) {
    const i = p * ch;
    if (src[i + 3] < 1) continue;
    const m = M[p];
    const brT = steel[0] + m * (rust[0] - steel[0]);
    const grT = steel[1] + m * (rust[1] - steel[1]);
    const r = src[i], g = src[i + 1], b = src[i + 2];
    const L0 = L709(r, g, b);
    if (L0 < 1e-6) continue;
    // choose R so that (R, R*grT, R*brT) has luma L0
    const wsum = 0.2126 + 0.7152 * grT + 0.0722 * brT;
    const R = L0 / wsum;
    const v = [R, R * grT, R * brT];
    let cl = false;
    for (let c = 0; c < 3; c++) { if (v[c] > 255) { v[c] = 255; cl = true; } if (v[c] < 0) { v[c] = 0; cl = true; } }
    if (cl) clipped++;
    for (let c = 0; c < 3; c++) out[i + c] = Math.round(v[c]);
  }
  return { buf: out, clipped };
}
/**
 * MATT instead of GLOSSY. A specular highlight is the bright tail, not the
 * whole level: soft-knee compression above a knee T, strength Q. Hue is
 * untouched (one scalar per pixel).
 *   T = knee as a MULTIPLE of p70, Q = how hard the tail is squashed
 * The point of measuring meso afterwards is that this must not flatten the
 * tile -- flatness has been rejected three times this round.
 */
function matt(src, ch, w, h, p70, T, Q) {
  const knee = T * p70;
  const out = Buffer.from(src);
  for (let p = 0; p < w * h; p++) {
    const i = p * ch;
    if (src[i + 3] < 1) continue;
    const L = L709(src[i], src[i + 1], src[i + 2]);
    if (L <= knee || L < 1e-6) continue;
    const e = L - knee;
    const Lp = knee + e / (1 + Q * e / knee);
    const k = Lp / L;
    for (let c = 0; c < 3; c++) { const v = src[i + c] * k; out[i + c] = v < 0 ? 0 : v > 255 ? 255 : Math.round(v); }
  }
  return out;
}
/** how much of the tile is specular tail: share of opaque pixels above k*p70 */
function specular(src, ch, w, h) {
  const lv = [];
  for (let p = 0; p < w * h; p++) { const i = p * ch; if (src[i + 3] < 250) continue;
    lv.push(L709(src[i], src[i + 1], src[i + 2])); }
  lv.sort((a, b) => a - b);
  const q = (t) => lv[Math.min(lv.length - 1, Math.floor(lv.length * t))];
  const p70 = q(0.70);
  const above = (k) => lv.filter((v) => v > k * p70).length / lv.length;
  return { p70, p99: q(0.99), p999: q(0.999), max: lv[lv.length - 1],
    spec14: 100 * above(1.4), spec16: 100 * above(1.6), spec18: 100 * above(1.8),
    tail: q(0.999) / p70 };
}
module.exports = { dualBasis, selfTest, torusNoise, corrosionMask, corrode, matt, specular, smooth };
