/**
 * PRODUCTION: volcanic_vent 4-slot build — the ACTIVE / HOTTER cousin of lava_flow.
 *
 * Rudi picked candidate v3 from scripts/style-test-tile-volcanic-vent.cjs:
 *   slot 0 = assets/style-test/tiles/volcanic_vent_v3.png  (ALREADY generated =
 *            kontext-edit of lava_flow_l2; 512x256 diamond-masked RGBA — yellow-white
 *            hot cores, wider molten coverage, strongest glow). Used DIRECTLY, NO flop.
 *
 * The other 3 slots are built by applying the SAME v3 kontext approach (the EXACT v3
 * prompt, verbatim, + the gentle equalize2DSoft EQ_STRENGTH=0.35 that preserves the
 * bright hot cores) to the three finished lava_flow slot SOURCES, so all 4
 * volcanic_vent slots share the same HOT active fissure network:
 *   slot 1 = kontext-edit(v3 prompt) of lava_flow_d1   (no flop)
 *   slot 2 = kontext-edit(v3 prompt) of lava_flow_d2   (.flop L<->R)
 *   slot 3 = kontext-edit(v3 prompt) of lava_flow_d3   (.flop L<->R)
 * Slots 2 & 3 mirror on the VERTICAL axis (sharp .flop = left<->right) to fight visible
 * repetition; never .flip (top<->bottom) — that breaks the upper-left lighting convention.
 *
 * EQUALIZE NOTE: this uses the GENTLE equalize2DSoft() from
 * scripts/style-test-tile-volcanic-vent.cjs (NOT the full-strength equalize2D from the
 * lava_flow/obsidian derive scripts). The full equalize divides by a blurred copy and
 * re-multiplies by the global mean, which drags the bright yellow/yellow-white hot cores
 * back toward the mean and KILLS the glow that IS volcanic_vent. equalize2DSoft blends the
 * flattened result with the original at EQ_STRENGTH=0.35 so a global gradient is still
 * toned down while the hot cores + bloom survive.
 *
 * Per tile writes (matching the existing lava_flow / obsidian_ridge bestand exactly):
 *   volcanic_vent_<n>.webp                full 512x256   (webp q90 e4)
 *   volcanic_vent_<n>@half.{webp,png}     256x128
 *   volcanic_vent_<n>@quarter.{webp,png}  128x64
 *   volcanic_vent_<n>@eighth.{webp,png}   64x32
 * Overwrites the OLD originals + mips in src/assets/tiles/volcanic_vent/.
 *
 * fal key in scripts/.env (FAL_AI_API_KEY) — never hardcode / commit.
 *
 * Usage:
 *   node scripts/volcanic-vent-build-from-lava.cjs              full run (derive d1/d2/d3 + integrate)
 *   node scripts/volcanic-vent-build-from-lava.cjs --derive-only [d1 d2 d3]   re-roll a derivative (seed +1000)
 *   node scripts/volcanic-vent-build-from-lava.cjs --integrate-only           rebuild src from existing derivatives
 *   node scripts/volcanic-vent-build-from-lava.cjs d2=541777                  re-roll d2 with an explicit fresh seed
 */
